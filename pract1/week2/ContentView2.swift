import SwiftUI

// An enum defines a fixed set of possible values.
// CaseIterable allows us to access all cases using MuscleGroup.allCases.
enum MuscleGroup: CaseIterable {
    case chest
    case back
    case arms
    case shoulders
    case legs
    
}

// An extension adds functionality to an existing type without modifying its original definition.

// * Computed property : A computed property calculates its value when accessed. It does not store a separate value in memory.

extension MuscleGroup {
    
    var displayName: String {
        switch self {
        case .chest:
            return "chest group"
        case .back:
            return "back group"
        case .arms:
            return "arms group"
        case .shoulders:
            return "shoulders group"
        case .legs:
            return "legs group"
        }
    }
}

struct Workout {
    let name: String    // Stored property
    let muscleGroup: MuscleGroup
    let duration: Int
    
    // lazy property : A lazy stored property is initialized only when it is first accessed. It must be declared with 'var' because its value is assigned later.
    
//    lazy var iit: String = {
//        // some complex logic
//        return "iit"
//    }()
}




struct ContentView2: View {
    // An array containing Workout instances.
        // Each instance is created using the memberwise initializer generated by Swift.
    
    let workouts = [
          Workout(name: "Bench Press", muscleGroup: .chest, duration: 45),
          Workout(name: "Incline Bench Press", muscleGroup: .chest, duration: 45),
          Workout(name: "Squats", muscleGroup: .legs, duration: 60),
          Workout(name: "PullUps", muscleGroup: .back, duration: 30)
    ]
    
    var body: some View {
        List(workouts, id:\.name) { workout in
            Text(workout.name)
        }
    }
}

